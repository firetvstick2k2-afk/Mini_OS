inline bool decodeBase64(const char* input, uint8_t* output, size_t capacity, size_t& written) {
  static const char alphabet[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  written = 0;
  if (!input || !output) return false;
  uint32_t accumulator = 0;
  uint8_t bits = 0;
  for (size_t i = 0; input[i]; ++i) {
    const char ch = input[i];
    if (ch == '=') break;
    const char* found = strchr(alphabet, ch);
    if (!found) return false;
    accumulator = (accumulator << 6) | static_cast<uint32_t>(found - alphabet);
    bits = static_cast<uint8_t>(bits + 6);
    if (bits >= 8) {
      bits = static_cast<uint8_t>(bits - 8);
      if (written >= capacity) return false;
      output[written++] = static_cast<uint8_t>((accumulator >> bits) & 0xFF);
    }
  }
  return written != 0;
}

inline const char* encoded(uint8_t profile, bool ssb) {
  if (profile == 1) return ssb ? kV1Ssb : kV1Am;
  if (profile == 2) return ssb ? kV2Ssb : kV2Am;
  return nullptr;
}
